/* The terminal caps its ASCII bars at 38 blocks, which is right for a terminal
   and wrong for a chart: on a dense surface eight of nine rows hit the cap and
   render identically, so 171 and 2,154 read as equal. Here the bar is
   proportional to the row maximum and a dotted rule marks where the terminal
   stops drawing. Departing from the terminal is the honest choice — a chart
   whose lengths do not encode its numbers is misinformation with a legend. */
function renderGraph(s) {
  /* Scaled to the largest *lever* type, not the largest type outright.
     `attribute` is the heuristic extractor's dump bucket — the documented
     ceiling is that it absorbs roughly three claims in four — so it is
     routinely an order of magnitude above every row that carries meaning, and
     scaling to it flattens the whole chart into stubs. It overflows the track
     instead, hatched, with its real number beside it. Excluding a known
     junk bucket from the scale is a judgement; hiding that it overflowed
     would not be, which is why the overflow is drawn. */
  const levers = TYPE_ROWS.filter(([t]) => t !== 'attribute').map(([t]) => s.types[t] || 0);
  const max = Math.max(...levers, 1);
  const showCap = max > BAR_CAP;

  $('#graph').innerHTML = TYPE_ROWS.map(([type, lever]) => {
    const n = s.types[type] || 0;
    const over = n > max;
    const pct = Math.min(100, (n / max) * 100);
    const capPct = Math.min(100, (BAR_CAP / max) * 100);
    return `
      <div class="grow ${n ? '' : 'zero'}">
        <span class="t">${type}</span>
        <span class="c">${num(n)}</span>
        <span class="bartrack">
          <span class="barwrap">
            ${n ? `<span class="bar ${over ? 'over' : ''}" style="width:${pct}%"></span>` : ''}
            ${showCap ? `<span class="capmark" style="left:${capPct}%"></span>` : ''}
          </span>
          ${over ? '<span class="lever off">← off the scale, and not a lever</span>'
                 : n && lever ? `<span class="lever ${type === 'quantity' ? 'hot' : ''}">← ${lever}</span>`
                 : ''}
        </span>
      </div>`;
  }).join('');

  $('#capNote').hidden = !showCap;
}

function renderVerdicts(s) {
  $('#verdicts').innerHTML = s.forms.map((f) => `
    <div class="vrow ${f.ok ? 'ok' : 'no'}">
      <span class="vmark">${f.ok ? '✓ MINTABLE' : '✗ REFUSED'}</span>
      <span class="vname">${esc(f.name)}</span>
      <span class="vcount">${f.have}/${f.need} ${f.type}</span>
    </div>`).join('');
}

function renderFinds(s) {
  const f = s.findings;
  const cell = (label, value, kind) =>
    `<div class="find ${kind || ''}"><b>${value}</b>${label}</div>`;
  $('#finds').innerHTML = [
    s.blocked.length
      ? cell('AI crawlers blocked', s.blocked.length, 'warn')
      : cell('robots.txt clear', '✓', 'good'),
    cell('self-contradictions', f.contradictions, f.contradictions ? 'warn' : ''),
    cell('duplicate-URL groups', f.duplicate_urls, f.duplicate_urls ? 'warn' : ''),
    cell('orphaned value pages', f.orphans, f.orphans ? 'warn' : ''),
    cell('unsourced quantities', f.unsourced, f.unsourced ? 'warn' : ''),
    cell(`of ${s.pages} pages, no schema`, f.no_schema, f.no_schema ? 'warn' : ''),
  ].join('');
}

function renderMaterial(s) {
  $('#material').innerHTML = s.material.length
    ? s.material.map((m) => `
        <div class="mrow">
          <span class="mt">${esc(m.type)}</span>
          <span class="mq">“${esc(m.text)}”</span>
          <span class="mu">${esc(m.url)}</span>
        </div>`).join('')
    : `<p class="caption" style="margin:0">No claim on this surface falls in the excerpt
       window. That is what a one-page brochure site looks like from here.</p>`;
}

/* A surface that returns zero claims is not a broken panel — on three of these
   it is the single largest finding in the run, and blanking the pane would hide
   it. The crawler flagged the pages needs_headless, so it knows the difference
   between "nothing here" and "nothing I can read". */
function renderEmpty(s) {
  const box = $('#emptyNote');
  const isEmpty = s.claims === 0;
  box.hidden = !isEmpty;
  if (!isEmpty) return;
  box.innerHTML = `
    <div class="vhead">0 claims — and that is the finding</div>
    <p><b>${esc(s.domain)}</b> returned ${s.pages} page${s.pages === 1 ? '' : 's'},
    HTTP 200, and <b>${s.words} words of extractable text</b>. The content is real; it is
    inside a JSON blob in a <code>&lt;script&gt;</code> tag, so an engine's crawler sees
    what this crawler saw — nothing. Not blocked by <code>robots.txt</code>; simply
    unreadable.</p>
    <p style="margin-top:10px">Across the three documentation hosts in this list that is
    <b>458,382 words</b> and <b>229 documents</b> dark — 6.2× everything else on this page
    combined. No keyword tool surfaces it, because there are no keywords to see.</p>`;
}

