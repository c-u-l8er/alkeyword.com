function paintRefusal() {
  const f = FORMS[formIdx];
  const have = +slider.value;
  const d = FORM_DETAIL[f.type];
  const ok = have >= f.need;

  slider.style.setProperty('--pct', (have / +slider.max * 100) + '%');
  $('#clOut').textContent = have;

  const box = $('#verdictBox');
  box.classList.toggle('ok', ok);
  box.classList.toggle('no', !ok);
  $('#vbHead').textContent = ok ? '✓ mintable' : '✗ refused';
  $('#vbBody').innerHTML = ok
    ? `You have <b>${have}</b> ${d.unit} and a ${esc(f.name.toLowerCase())} needs
       <b>${f.need}</b>. Enough material — this becomes a brief, with every claim attached
       verbatim and its source URL beside it.`
    : `<b>Not yet.</b> A ${esc(f.name.toLowerCase())} needs <b>${f.need}</b> ${d.unit},
       ${esc(d.extra)}. You have <b>${have}</b>. Gather <b>${f.need - have}</b> more and this
       becomes a ready brief — until then the honest answer is that there is nothing here to
       transmute.`;
}

