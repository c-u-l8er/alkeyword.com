/* ------------------------------------------------------------------ hero report

   A condensed stage-1 report, rendered from the same numbers the explorer
   uses, then typed in line by line. Condensed because the full report is 40
   lines and a hero is not a scroll target — every line shown is verbatim in
   shape and content, just fewer of them. */

function heroLines(s) {
  const t = s.types;
  const pad = (str, n) => String(str).padEnd(n);
  const lpad = (str, n) => String(str).padStart(n);
  const L = [];

  L.push(`<span class="d">crawling… ${s.pages} pages, ${num(s.words)} words</span>`);
  L.push('');
  L.push('CLAIM GRAPH');
  for (const [type, lever] of TYPE_ROWS) {
    const n = t[type] || 0;
    if (!n && type !== 'question' && type !== 'process') continue;
    const bar = '█'.repeat(Math.min(BAR_CAP, n));
    const tail = n && lever ? `  <span class="d">← ${lever}</span>` : '';
    L.push(`  ${pad(type, 12)}${lpad(n, 4)}  <span class="g">${bar}</span>${tail}`);
  }
  L.push('');
  L.push('MINTABLE');
  for (const f of s.forms) {
    const mark = f.ok ? '<span class="v">✓</span>' : '<span class="r">✗</span>';
    const why = f.ok ? '' : ' <span class="d">— refused, not enough material</span>';
    L.push(`  ${mark} ${pad(f.name, 24)} ${f.have}/${f.need} ${f.type}${why}`);
  }
  L.push('');
  L.push('FREE FINDINGS <span class="d">(no model calls spent)</span>');
  L.push(s.blocked.length
    ? `  <span class="r">⚠</span> robots.txt blocks ${esc(s.blocked.join(', '))}`
    : '  <span class="v">✓</span> robots.txt does not block AI crawlers');
  const f = s.findings;
  if (f.duplicate_urls) L.push(`  <span class="r">⚠</span> ${f.duplicate_urls} duplicate-URL groups   <span class="d">no canonical between them</span>`);
  if (f.orphans)        L.push(`  <span class="r">⚠</span> ${f.orphans} orphaned value pages`);
  if (f.unsourced)      L.push(`  <span class="r">⚠</span> ${f.unsourced} unsourced quantities`);
  L.push(`  <span class="r">⚠</span> ${f.no_schema} of ${s.pages} pages have no schema markup`);
  return L;
}

function typeIn(el, lines) {
  if (reduced) { el.innerHTML = lines.join('\n'); return; }
  el.innerHTML = '';
  let i = 0;
  const caret = '<span class="caret"></span>';
  const step = () => {
    el.innerHTML = lines.slice(0, i).join('\n') + (i < lines.length ? '\n' + caret : '');
    if (i++ < lines.length) setTimeout(step, lines[i - 1] === '' ? 40 : 55);
  };
  step();
}

